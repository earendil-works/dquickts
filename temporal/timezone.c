static BOOL tz_is_link_alias(const char *name)
{
    int i;
    for (i = 0; i < (int)countof(tz_aliases); i++) {
        if (!strcasecmp(name, tz_aliases[i][0]))
            return TRUE;
    }
    return FALSE;
}

static int tz_strcmp_ptr(const void *a, const void *b)
{
    return strcmp(*(const char * const *)a, *(const char * const *)b);
}

/* Sorted list of the embedded zones and of the primary zones of the tz
   database. Must be called with tz_db_mutex locked. */
static void tz_init_primary_names(void)
{
    char path[512];
    const char **names, *name;
    int i, count;

    if (tz_primary_names)
        return;
    tz_db_init_index();
    names = malloc(sizeof(names[0]) * (ti_tz_zone_count + tz_db_zone_count));
    if (!names)
        return;
    count = 0;
    for (i = 0; i < ti_tz_zone_count; i++)
        names[count++] = ti_tz_zone_data[i].canonical_name;
    for (i = 0; i < tz_db_zone_count; i++) {
        name = tz_db_zones[i];
        if (!tz_is_db_name(name) || tz_embedded_find_id(name) >= 0 ||
            tz_is_link_alias(name))
            continue;
        snprintf(path, sizeof(path), "%s/%s", tz_db_dir, name);
        if (access(path, R_OK) != 0)
            continue;
        names[count++] = name;
    }
    qsort(names, count, sizeof(names[0]), tz_strcmp_ptr);
    tz_primary_count = count;
    tz_primary_names = names;
}

/* Find or load a zone of the tz database. Return its index in
   tz_dyn_zones[] or -1. */
static int tz_dyn_find(const char *name)
{
    char path[512], canon[TZ_NAME_MAX];
    uint8_t *buf;
    size_t len;
    TZDynZone *z;
    int i, ret = -1;

    if (!tz_is_db_name(name))
        return -1;
    pthread_mutex_lock(&tz_db_mutex);
    for (i = 0; i < tz_dyn_count; i++) {
        if (!strcasecmp(tz_dyn_zones[i]->name, name)) {
            ret = i;
            goto done;
        }
    }
    for (i = 0; i < TZ_NEG_CACHE_SIZE; i++) {
        if (!strcasecmp(tz_neg_cache[i], name))
            goto done;
    }
    tz_db_init_dir();
    if (!tz_db_dir[0] ||
        !tz_db_resolve(name, path, sizeof(path), canon, sizeof(canon))) {
        pstrcpy(tz_neg_cache[tz_neg_cache_pos], TZ_NAME_MAX, name);
        tz_neg_cache_pos = (tz_neg_cache_pos + 1) % TZ_NEG_CACHE_SIZE;
        goto done;
    }
    if (tz_dyn_count >= TZ_DYN_MAX)
        goto done;
    buf = tz_read_file(path, &len);
    if (!buf)
        goto done;
    z = tz_parse_tzif(buf, len);
    free(buf);
    if (!z)
        goto done;
    pstrcpy(z->name, sizeof(z->name), canon);
    tz_db_init_index();
    z->primary = tz_db_link_target(z->name);
    ret = tz_dyn_count;
    tz_dyn_zones[tz_dyn_count++] = z;
 done:
    pthread_mutex_unlock(&tz_db_mutex);
    return ret;
}

#endif /* TZ_SYSTEM_DB */

static BOOL tz_get_view(int tz_id, TZView *v)
{
    if (tz_id >= 0 && tz_id < ti_tz_zone_count) {
        v->tr = ti_tz_zone_data[tz_id].transitions;
        v->n = ti_tz_zone_data[tz_id].transition_count;
        v->rule = NULL;
        return TRUE;
    }
#ifdef TZ_SYSTEM_DB
    if (tz_id >= ti_tz_zone_count && tz_id - ti_tz_zone_count < TZ_DYN_MAX) {
        const TZDynZone *z = tz_dyn_zones[tz_id - ti_tz_zone_count];
        if (z) {
            v->tr = z->tr;
            v->n = z->n;
            v->rule = z->has_rule ? &z->rule : NULL;
            return TRUE;
        }
    }
#endif
    return FALSE;
}

static const char *ti_tz_canonical_name(int tz_id) {
    if (tz_id < 0)
        return NULL;
    if (tz_id < ti_tz_zone_count)
        return ti_tz_zone_data[tz_id].canonical_name;
#ifdef TZ_SYSTEM_DB
    if (tz_id - ti_tz_zone_count < TZ_DYN_MAX) {
        const TZDynZone *z = tz_dyn_zones[tz_id - ti_tz_zone_count];
        if (z)
            return z->primary ? z->primary : z->name;
    }
#endif
    return NULL;
}

const char *ti_canonicalize_timezone_alias(const char *tz)
{
    int i;
    int n = (int)(sizeof(tz_aliases) / sizeof(tz_aliases[0]));
    for (i = 0; i < n; i++) {
        if (strcmp(tz, tz_aliases[i][0]) == 0)
            return tz_aliases[i][1];
        if (strcmp(tz, tz_aliases[i][1]) == 0)
            return tz_aliases[i][1];
    }
    int id = ti_tz_find_id(tz);
    if (id >= 0) {
        const char *canon = ti_tz_canonical_name(id);
        if (canon)
            return canon;
    }
    return tz;
}

BOOL ti_timezones_are_equal(const char *tz1, const char *tz2)
{
    if (strcmp(tz1, tz2) == 0)
        return TRUE;
    if (strcasecmp(tz1, tz2) == 0)
        return TRUE;
    const char *c1 = ti_canonicalize_timezone_alias(tz1);
    const char *c2 = ti_canonicalize_timezone_alias(tz2);
    return strcmp(c1, c2) == 0;
}

static int tz_embedded_find_id(const char *name)
{
    int i;
    for (i = 0; i < ti_tz_alias_count; i++) {
        if (strcasecmp(name, ti_tz_aliases[i].alias) == 0)
            return ti_tz_aliases[i].canonical_id;
    }
    for (i = 0; i < ti_tz_zone_count; i++) {
        if (strcasecmp(name, ti_tz_zone_data[i].canonical_name) == 0)
            return i;
    }
    return -1;
}

/* The embedded zones take precedence over the system tz database */
int ti_tz_find_id(const char *name)
{
    int id = tz_embedded_find_id(name);
#ifdef TZ_SYSTEM_DB
    if (id < 0) {
        id = tz_dyn_find(name);
        if (id >= 0)
            id += ti_tz_zone_count;
    }
#endif
    return id;
}

int ti_tz_primary_name_count(void)
{
#ifdef TZ_SYSTEM_DB
    int count;
    pthread_mutex_lock(&tz_db_mutex);
    tz_init_primary_names();
    count = tz_primary_names ? tz_primary_count : ti_tz_zone_count;
    pthread_mutex_unlock(&tz_db_mutex);
    return count;
#else
    return ti_tz_zone_count;
#endif
}

/* must be called after ti_tz_primary_name_count() */
const char *ti_tz_primary_name(int i)
{
#ifdef TZ_SYSTEM_DB
    if (tz_primary_names)
        return tz_primary_names[i];
#endif
    return ti_tz_zone_data[i].canonical_name;
}

int ti_tz_offset_at_sec(int tz_id, int64_t epoch_sec) {
    TZView v;
    int64_t lo;
    if (!tz_get_view(tz_id, &v))
        return 0;
    lo = tz_count_le(&v, epoch_sec);
    if (lo > 0)
        return tz_get_offset(&v, lo - 1);
    return 0;
}

int64_t ti_tz_next_transition_sec(int tz_id, int64_t epoch_sec) {
    TZView v;
    int64_t lo;
    if (!tz_get_view(tz_id, &v))
        return INT64_MIN;
    lo = tz_count_le(&v, epoch_sec);
    if (tz_has_tr(&v, lo))
        return tz_get_time(&v, lo);
    return INT64_MIN;
}

int64_t ti_tz_next_transition_at(int tz_id, int64_t epoch_sec, int epoch_nsec) {
    TZView v;
    int64_t lo;
    if (!tz_get_view(tz_id, &v))
        return INT64_MIN;
    if (epoch_nsec >= 0 || epoch_sec == INT64_MIN)
        lo = tz_count_le(&v, epoch_sec);
    else
        lo = tz_count_le(&v, epoch_sec - 1);
    /* Skip no-op transitions where the offset doesn't change */
    while (tz_has_tr(&v, lo) && tz_get_offset(&v, lo) == tz_get_offset(&v, lo - 1))
        lo++;
    if (tz_has_tr(&v, lo))
        return tz_get_time(&v, lo);
    return INT64_MIN;
}

int64_t ti_tz_prev_transition_at(int tz_id, int64_t epoch_sec, int epoch_nsec) {
    TZView v;
    int64_t i;
    if (!tz_get_view(tz_id, &v))
        return INT64_MIN;
    if (epoch_nsec > 0 || epoch_sec == INT64_MIN)
        i = tz_count_le(&v, epoch_sec) - 1;
    else
        i = tz_count_le(&v, epoch_sec - 1) - 1;
    /* Skip no-op transitions where the offset doesn't change */
    while (i >= 1 && tz_get_offset(&v, i) == tz_get_offset(&v, i - 1))
        i--;
    if (i >= 1)
        return tz_get_time(&v, i);
    return INT64_MIN;
}

int ti_tz_prev_offset_at_sec(int tz_id, int64_t epoch_sec) {
    TZView v;
    int64_t lo;
    if (!tz_get_view(tz_id, &v))
        return 0;
    lo = tz_count_le(&v, epoch_sec);
    /* lo-1 is the active transition, lo-2 is the previous one */
    if (lo > 1)
        return tz_get_offset(&v, lo - 2);
    return v.tr[0].offset_sec;
}

/* Convert local wall-clock time to UTC epoch for a named timezone.
   dis_idx: 0=earlier, 1=later, 2=compatible, 3=reject.
   Returns 0 on success, -1 if reject disambiguation throws (caller should throw RangeError).
   On success, *out_utc_sec and *out_offset_sec are set. */
int ti_tz_local_to_utc(int tz_id, int64_t local_sec, int dis_idx,
                        int64_t *out_utc_sec, int *out_offset_sec)
{
    int64_t guess_sec = local_sec;
    int iter;
    int converged = 0;
    int64_t utc1 = 0;
    int offset1 = 0;

    for (iter = 0; iter < 4; iter++) {
        int offset_sec = ti_tz_offset_at_sec(tz_id, guess_sec);
        int64_t new_sec = local_sec - offset_sec;
        if (new_sec == guess_sec) {
            utc1 = guess_sec;
            offset1 = offset_sec;
            converged = 1;
            break;
        }
        guess_sec = new_sec;
    }

    if (converged) {
        /* Check for ambiguity (overlap): another candidate with prev offset */
        int prev_offset = ti_tz_prev_offset_at_sec(tz_id, utc1);
        if (prev_offset != offset1) {
            int64_t cand2 = local_sec - prev_offset;
            if (cand2 != utc1 && ti_tz_offset_at_sec(tz_id, cand2) == prev_offset) {
                /* Two candidates - sort by UTC time */
                int64_t earlier_utc, later_utc;
                int earlier_offset, later_offset;
                if (cand2 < utc1) {
                    earlier_utc = cand2;
                    earlier_offset = prev_offset;
                    later_utc = utc1;
                    later_offset = offset1;
                } else {
                    earlier_utc = utc1;
                    earlier_offset = offset1;
                    later_utc = cand2;
                    later_offset = prev_offset;
                }
                if (dis_idx == 3) /* reject */
                    return -1;
                if (dis_idx == 1) { /* later */
                    *out_utc_sec = later_utc;
                    *out_offset_sec = later_offset;
                } else { /* compatible / earlier */
                    *out_utc_sec = earlier_utc;
                    *out_offset_sec = earlier_offset;
                }
                return 0;
            }
        }
        /* Single candidate */
        *out_utc_sec = utc1;
        *out_offset_sec = offset1;
        return 0;
    } else {
        /* Gap - no converged value */
        int64_t guess1 = guess_sec;
        int offset_guess1 = ti_tz_offset_at_sec(tz_id, guess1);
        int64_t guess2 = local_sec - offset_guess1;
        int offset_guess2 = ti_tz_offset_at_sec(tz_id, guess2);
        int64_t mapped_local1 = guess1 + offset_guess1;
        int64_t mapped_local2 = guess2 + offset_guess2;

        if (dis_idx == 3) /* reject */
            return -1;

        if (dis_idx == 0) { /* earlier: use candidate mapping to earlier local time */
            if (mapped_local1 < mapped_local2) {
                *out_utc_sec = guess1;
                *out_offset_sec = offset_guess1;
            } else {
                *out_utc_sec = guess2;
                *out_offset_sec = offset_guess2;
            }
        } else { /* compatible / later */
            if (mapped_local1 > mapped_local2) {
                *out_utc_sec = guess1;
                *out_offset_sec = offset_guess1;
            } else {
                *out_utc_sec = guess2;
                *out_offset_sec = offset_guess2;
            }
        }
        return 0;
    }
}

/* GetStartOfDay: return the UTC epoch for the start of a local day.
   Uses the spec GetStartOfDay algorithm:
   - Try earlier disambiguation for midnight local time
   - If midnight maps back correctly, that's the start of day
   - Otherwise (gap at midnight), return the next transition after (midnight - 1 day)
   Returns the UTC epoch, or INT64_MIN on error (should not happen for valid days). */
int64_t ti_get_start_of_day_sec(int tz_id, int64_t local_day_start_sec)
{
    int64_t utc_sec;
    int out_offset_sec;
    if (ti_tz_local_to_utc(tz_id, local_day_start_sec, 0, &utc_sec, &out_offset_sec) < 0)
        return INT64_MIN;
    if (utc_sec + ti_tz_offset_at_sec(tz_id, utc_sec) == local_day_start_sec)
        return utc_sec;
    /* Gap at midnight: return the next transition after (midnight - 1 day) */
    {
        int64_t next_trans = ti_tz_next_transition_sec(tz_id, local_day_start_sec - 86400LL);
        if (next_trans != INT64_MIN)
            return next_trans;
    }
    return utc_sec;
}
