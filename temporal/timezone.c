static uint32_t tz_get_be32(const uint8_t *p)
{
    return ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) |
        ((uint32_t)p[2] << 8) | p[3];
}

static int64_t tz_get_be32s(const uint8_t *p)
{
    uint32_t v = tz_get_be32(p);
    return v >= 0x80000000 ? (int64_t)v - ((int64_t)1 << 32) : (int64_t)v;
}

static int64_t tz_get_be64s(const uint8_t *p)
{
    uint64_t v = ((uint64_t)tz_get_be32(p) << 32) | tz_get_be32(p + 4);
    return v >> 63 ? -(int64_t)~v - 1 : (int64_t)v;
}

static BOOL tz_is_digit(int c)
{
    return c >= '0' && c <= '9';
}

static BOOL tz_is_alpha(int c)
{
    return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z');
}

/* POSIX TZ string parsing */

static const char *tz_parse_abbr(const char *p)
{
    const char *q;
    if (*p == '<') {
        q = strchr(p, '>');
        return q ? q + 1 : NULL;
    }
    q = p;
    while (tz_is_alpha(*p))
        p++;
    return p - q >= 3 ? p : NULL;
}

static const char *tz_parse_uint(const char *p, int max_digits, int max,
                                 int *pval)
{
    int v = 0, n = 0;
    while (tz_is_digit(*p) && n < max_digits) {
        v = v * 10 + (*p++ - '0');
        n++;
    }
    if (n == 0 || v > max)
        return NULL;
    *pval = v;
    return p;
}

/* [+-]hh[:mm[:ss]] */
static const char *tz_parse_time(const char *p, int max_hours, int32_t *psecs)
{
    int sign = 1, h, m = 0, s = 0;
    if (*p == '+' || *p == '-') {
        if (*p == '-')
            sign = -1;
        p++;
    }
    p = tz_parse_uint(p, 3, max_hours, &h);
    if (p && *p == ':') {
        p = tz_parse_uint(p + 1, 2, 59, &m);
        if (p && *p == ':')
            p = tz_parse_uint(p + 1, 2, 59, &s);
    }
    if (p)
        *psecs = sign * (h * 3600 + m * 60 + s);
    return p;
}

static const char *tz_parse_rule_date(const char *p, TZRuleDate *rd)
{
    int month, week, wday, day;
    if (*p == 'M') {
        p = tz_parse_uint(p + 1, 2, 12, &month);
        if (!p || *p != '.' || month == 0)
            return NULL;
        p = tz_parse_uint(p + 1, 1, 5, &week);
        if (!p || *p != '.' || week == 0)
            return NULL;
        p = tz_parse_uint(p + 1, 1, 6, &wday);
        if (!p)
            return NULL;
        rd->type = TZ_RULE_MWD;
        rd->month = month;
        rd->week = week;
        rd->wday = wday;
    } else if (*p == 'J') {
        p = tz_parse_uint(p + 1, 3, 365, &day);
        if (!p || day == 0)
            return NULL;
        rd->type = TZ_RULE_JULIAN1;
        rd->day = day;
    } else {
        p = tz_parse_uint(p, 3, 365, &day);
        if (!p)
            return NULL;
        rd->type = TZ_RULE_JULIAN0;
        rd->day = day;
    }
    rd->secs = 2 * 3600;
    if (*p == '/')
        p = tz_parse_time(p + 1, 167, &rd->secs);
    return p;
}

/* Parse the POSIX TZ string of a TZif footer. Return TRUE if it
   defines daylight saving time rules. */
static BOOL tz_parse_posix_rule(const char *p, TZRule *r)
{
    int32_t std_secs, dst_secs;

    p = tz_parse_abbr(p);
    if (!p)
        return FALSE;
    p = tz_parse_time(p, 24, &std_secs);
    if (!p || *p == '\0')
        return FALSE;
    p = tz_parse_abbr(p);
    if (!p)
        return FALSE;
    dst_secs = std_secs - 3600;
    if (*p != ',' && *p != '\0') {
        p = tz_parse_time(p, 24, &dst_secs);
        if (!p)
            return FALSE;
    }
    if (*p == '\0') {
        /* default rule: M3.2.0,M11.1.0 */
        r->start.type = TZ_RULE_MWD;
        r->start.month = 3;
        r->start.week = 2;
        r->start.wday = 0;
        r->start.secs = 2 * 3600;
        r->end = r->start;
        r->end.month = 11;
        r->end.week = 1;
    } else {
        if (*p != ',')
            return FALSE;
        p = tz_parse_rule_date(p + 1, &r->start);
        if (!p || *p != ',')
            return FALSE;
        p = tz_parse_rule_date(p + 1, &r->end);
        if (!p || *p != '\0')
            return FALSE;
    }
    /* POSIX offsets are positive west of Greenwich */
    r->std_offset = -std_secs;
    r->dst_offset = -dst_secs;
    return r->std_offset != r->dst_offset;
}

/* Set the first rule transition after 'last_time'. Return FALSE if the
   rule does not give alternating transitions (e.g. permanent DST). */
static BOOL tz_rule_init(TZRule *r, int64_t last_time)
{
    int64_t k;

    if (last_time < -TZ_RULE_MAX_SEC)
        last_time = -TZ_RULE_MAX_SEC;
    r->first_year = tz_year_from_days(tz_floor_div(last_time, 86400));
    r->first_index = 0;
    for (k = 0; k < 5; k++) {
        if (tz_rule_time(r, k) >= tz_rule_time(r, k + 1))
            return FALSE;
    }
    while (tz_rule_time(r, r->first_index) <= last_time)
        r->first_index++;
    return TRUE;
}

/* Parse a TZif file (RFC 9636) */
static TZDynZone *tz_parse_tzif(const uint8_t *buf, size_t len)
{
    /* isutcnt, isstdcnt, leapcnt, timecnt, typecnt, charcnt */
    uint32_t cnt[6];
    size_t pos, size, time_size, i, j;
    const uint8_t *times, *idx, *types, *footer;
    int version, offset;
    int64_t t, last_time;
    TZDynZone *z;
    char rule_str[256];

    if (len < 5)
        return NULL;
    version = buf[4];
    pos = 0;
    time_size = 4;
    for (;;) {
        if (len - pos < 44 || memcmp(buf + pos, "TZif", 4) != 0)
            return NULL;
        for (i = 0; i < 6; i++)
            cnt[i] = tz_get_be32(buf + pos + 20 + 4 * i);
        /* zones with leap seconds ("right/") are not supported */
        if (cnt[3] > 65536 || cnt[4] == 0 || cnt[4] > 256 ||
            cnt[5] > 65536 || cnt[2] != 0 ||
            (cnt[0] != 0 && cnt[0] != cnt[4]) ||
            (cnt[1] != 0 && cnt[1] != cnt[4]))
            return NULL;
        size = cnt[3] * (time_size + 1) + cnt[4] * 6 + cnt[5] + cnt[1] + cnt[0];
        pos += 44;
        if (size > len - pos)
            return NULL;
        if (time_size == 8 || version < '2')
            break;
        /* skip the version 1 data */
        pos += size;
        time_size = 8;
    }
    times = buf + pos;
    idx = times + cnt[3] * time_size;
    types = idx + cnt[3];
    for (i = 0; i < cnt[4]; i++) {
        t = tz_get_be32s(types + 6 * i);
        if (t < -26 * 3600 || t > 26 * 3600)
            return NULL;
    }
    z = malloc(sizeof(*z) + (cnt[3] + 1) * sizeof(z->tr[0]));
    if (!z)
        return NULL;
    memset(z, 0, sizeof(*z));
    z->n = cnt[3] + 1;
    z->tr[0].start_sec = INT64_MIN;
    z->tr[0].offset_sec = (int32_t)tz_get_be32s(types);
    last_time = INT64_MIN;
    for (i = 0; i < cnt[3]; i++) {
        if (time_size == 8)
            t = tz_get_be64s(times + 8 * i);
        else
            t = tz_get_be32s(times + 4 * i);
        if (t <= last_time || idx[i] >= cnt[4])
            goto fail;
        offset = (int)tz_get_be32s(types + 6 * idx[i]);
        z->tr[i + 1].start_sec = t;
        z->tr[i + 1].offset_sec = offset;
        last_time = t;
    }
    /* the footer gives the rule used after the last transition */
    if (version >= '2') {
        footer = buf + pos + size;
        len -= pos + size;
        if (len >= 2 && footer[0] == '\n') {
            for (j = 1; j < len && j < sizeof(rule_str) && footer[j] != '\n'; j++)
                rule_str[j - 1] = footer[j];
            if (j < len && footer[j] == '\n') {
                rule_str[j - 1] = '\0';
                if (tz_parse_posix_rule(rule_str, &z->rule))
                    z->has_rule = tz_rule_init(&z->rule, last_time);
            }
        }
    }
    return z;
 fail:
    free(z);
    return NULL;
}

/* Read a whole file. The result is null terminated. */
static uint8_t *tz_read_file(const char *path, size_t *plen)
{
    FILE *f;
    long size;
    uint8_t *buf = NULL;

    f = fopen(path, "rb");
    if (!f)
        return NULL;
    if (fseek(f, 0, SEEK_END) != 0)
        goto done;
    size = ftell(f);
    if (size < 0 || size > TZ_FILE_MAX || fseek(f, 0, SEEK_SET) != 0)
        goto done;
    buf = malloc(size + 1);
    if (!buf)
        goto done;
    if (fread(buf, 1, size, f) != (size_t)size) {
        free(buf);
        buf = NULL;
        goto done;
    }
    buf[size] = '\0';
    *plen = size;
 done:
    fclose(f);
    return buf;
}

/* Valid tz database zone name which can be looked up in the file system */
static BOOL tz_is_db_name(const char *name)
{
    size_t len = 0, comp_len = 0;
    char c;

    if (!tz_is_alpha(name[0]))
        return FALSE;
    for (; (c = name[len]) != '\0'; len++) {
        if (c == '/') {
            if (comp_len == 0)
                return FALSE;
            comp_len = 0;
        } else if (tz_is_alpha(c) || tz_is_digit(c) ||
                   c == '_' || c == '-' || c == '+') {
            comp_len++;
        } else {
            return FALSE;
        }
    }
    if (comp_len == 0 || len >= TZ_NAME_MAX)
        return FALSE;
    /* database files which are not time zones */
    if (!strcasecmp(name, "posixrules") || !strcasecmp(name, "localtime") ||
        !strcasecmp(name, "Factory") || !strncasecmp(name, "posix/", 6) ||
        !strncasecmp(name, "right/", 6))
        return FALSE;
    return TRUE;
}

/* must be called with tz_db_mutex locked */
static void tz_db_init_dir(void)
{
    static const char * const dirs[] = {
        "/usr/share/zoneinfo",
        "/var/db/timezone/zoneinfo",
        "/usr/share/lib/zoneinfo",
    };
    const char *dir;
    DIR *d;
    int i;

    if (tz_db_dir_init)
        return;
    tz_db_dir_init = TRUE;
    for (i = -1; i < (int)countof(dirs); i++) {
        dir = i < 0 ? getenv("TZDIR") : dirs[i];
        if (!dir || !dir[0] || strlen(dir) >= sizeof(tz_db_dir))
            continue;
        d = opendir(dir);
        if (d) {
            closedir(d);
            pstrcpy(tz_db_dir, sizeof(tz_db_dir), dir);
            return;
        }
    }
}

/* Look up 'name' in the tz database directory, matching the path
   components case-insensitively. 'path' receives the file path and
   'canon' the name as cased in the database. */
static BOOL tz_db_resolve(const char *name, char *path, int path_size,
                          char *canon, int canon_size)
{
    char comp[TZ_NAME_MAX], match[TZ_NAME_MAX];
    const char *p, *sep;
    struct dirent *de;
    size_t len;
    DIR *d;

    pstrcpy(path, path_size, tz_db_dir);
    canon[0] = '\0';
    for (p = name;; p = sep + 1) {
        sep = strchr(p, '/');
        len = sep ? (size_t)(sep - p) : strlen(p);
        memcpy(comp, p, len);
        comp[len] = '\0';
        d = opendir(path);
        if (!d)
            return FALSE;
        match[0] = '\0';
        while ((de = readdir(d)) != NULL) {
            if (!strcmp(de->d_name, comp)) {
                pstrcpy(match, sizeof(match), de->d_name);
                break;
            }
            if (!match[0] && !strcasecmp(de->d_name, comp))
                pstrcpy(match, sizeof(match), de->d_name);
        }
        closedir(d);
        if (!match[0])
            return FALSE;
        pstrcat(path, path_size, "/");
        pstrcat(path, path_size, match);
        if (canon[0])
            pstrcat(canon, canon_size, "/");
        pstrcat(canon, canon_size, match);
        if (!sep)
            return TRUE;
    }
}

static char *tz_copy_word(char **pnames, const char *p, size_t len)
{
    char *s = *pnames;
    memcpy(s, p, len);
    s[len] = '\0';
    *pnames = s + len + 1;
    return s;
}

/* Scan the "Z name ..." and "L target name" lines of tzdata.zi. If
   'names' is NULL, only count them. Return the size of the names. */
static size_t tz_db_scan_index(const char *buf, char *names,
                               const char **zones, int *pzone_count,
                               const char **links, int *plink_count)
{
    const char *p, *target, *link;
    size_t size = 0, n1, n2;
    int zone_count = 0, link_count = 0;

    for (p = buf; *p != '\0'; p += strcspn(p, "\n"), p += (*p == '\n')) {
        if (p[0] == 'Z' && p[1] == ' ') {
            n1 = strcspn(p + 2, " \n");
            if (names)
                zones[zone_count] = tz_copy_word(&names, p + 2, n1);
            zone_count++;
            size += n1 + 1;
        } else if (p[0] == 'L' && p[1] == ' ') {
            target = p + 2;
            n1 = strcspn(target, " \n");
            if (target[n1] != ' ')
                continue;
            link = target + n1 + 1;
            n2 = strcspn(link, " \n");
            if (names) {
                links[2 * link_count] = tz_copy_word(&names, link, n2);
                links[2 * link_count + 1] = tz_copy_word(&names, target, n1);
            }
            link_count++;
            size += n1 + n2 + 2;
        }
    }
    *pzone_count = zone_count;
    *plink_count = link_count;
    return size;
}

/* Read the zone and link names of tzdata.zi. Must be called with
   tz_db_mutex locked. */
static void tz_db_init_index(void)
{
    char path[512], *buf, *names;
    const char **zones, **links;
    size_t len, size;
    int zone_count, link_count;

    if (tz_db_index_init)
        return;
    tz_db_index_init = TRUE;
    tz_db_init_dir();
    if (!tz_db_dir[0])
        return;
    snprintf(path, sizeof(path), "%s/tzdata.zi", tz_db_dir);
    buf = (char *)tz_read_file(path, &len);
    if (!buf)
        return;
    size = tz_db_scan_index(buf, NULL, NULL, &zone_count, NULL, &link_count);
    names = malloc(size + 1);
    zones = malloc(sizeof(zones[0]) * (zone_count + 1));
    links = malloc(sizeof(links[0]) * (2 * link_count + 1));
    if (names && zones && links) {
        tz_db_scan_index(buf, names, zones, &zone_count, links, &link_count);
        tz_db_zones = zones;
        tz_db_zone_count = zone_count;
        tz_db_links = links;
        tz_db_link_count = link_count;
    } else {
        free(names);
        free(zones);
        free(links);
    }
    free(buf);
}

/* primary identifier of a link of the tz database or NULL */
static const char *tz_db_link_target(const char *name)
{
    const char *target = NULL;
    int i, depth;

    /* links to links are possible */
    for (depth = 0; depth < 8; depth++) {
        for (i = 0; i < tz_db_link_count; i++) {
            if (!strcmp(tz_db_links[2 * i], name))
                break;
        }
        if (i == tz_db_link_count)
            break;
        target = name = tz_db_links[2 * i + 1];
    }
    return target;
}

