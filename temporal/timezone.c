/* POSIX TZ string rule (TZif footer) giving the transitions after the
   last explicit one */
enum {
    TZ_RULE_JULIAN1, /* Jn: day 1 to 365, February 29 is never counted */
    TZ_RULE_JULIAN0, /* n: day 0 to 365, February 29 is counted */
    TZ_RULE_MWD,     /* Mm.w.d: day d (0 = Sunday) of week w of month m */
};

typedef struct {
    uint8_t type;
    uint8_t month;
    uint8_t week;
    uint8_t wday;
    int16_t day;
    int32_t secs; /* local time of day, may be negative or above 24 hours */
} TZRuleDate;

typedef struct {
    int32_t std_offset; /* seconds east of UTC */
    int32_t dst_offset;
    TZRuleDate start; /* DST start, in local standard time */
    TZRuleDate end; /* DST end, in local daylight time */
    int64_t first_year; /* year of the rule transitions 0 and 1 */
    int64_t first_index; /* first rule transition after the explicit ones */
} TZRule;

/* Transitions of a zone: the explicit transitions tr[0..n-1]
   (tr[0].start_sec is INT64_MIN and gives the initial offset) followed
   by the unbounded list of the transitions generated by 'rule' if not
   NULL. */
typedef struct {
    const TZTransition *tr;
    int n;
    const TZRule *rule;
} TZView;

/* bound of the rule computations to avoid overflows (35 million years) */
#define TZ_RULE_MAX_SEC ((int64_t)1 << 50)

static int64_t tz_floor_div(int64_t a, int64_t b)
{
    int64_t q = a / b;
    if (a % b < 0)
        q--;
    return q;
}

static int64_t tz_days_from_civil(int64_t y, int m, int d)
{
    int64_t era, yoe, doy, doe;
    if (m <= 2)
        y--;
    era = tz_floor_div(y, 400);
    yoe = y - era * 400;
    doy = (153 * (m > 2 ? m - 3 : m + 9) + 2) / 5 + d - 1;
    doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    return era * 146097 + doe - 719468;
}

static int64_t tz_year_from_days(int64_t days)
{
    int64_t z, era, doe, yoe, doy, mp;
    z = days + 719468;
    era = tz_floor_div(z, 146097);
    doe = z - era * 146097;
    yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
    doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    mp = (5 * doy + 2) / 153;
    return yoe + era * 400 + (mp >= 10);
}

/* day number since 1970-01-01 of a rule date */
static int64_t tz_rule_day(const TZRuleDate *rd, int64_t year)
{
    int64_t first, day, next;
    int wd;

    switch (rd->type) {
    case TZ_RULE_JULIAN1:
        day = tz_days_from_civil(year, 1, 1) + rd->day - 1;
        if (rd->day >= 60 && year % 4 == 0 &&
            (year % 100 != 0 || year % 400 == 0))
            day++;
        return day;
    case TZ_RULE_JULIAN0:
        return tz_days_from_civil(year, 1, 1) + rd->day;
    default:
        first = tz_days_from_civil(year, rd->month, 1);
        wd = (int)(first + 4 - tz_floor_div(first + 4, 7) * 7);
        day = first + (rd->wday - wd + 7) % 7 + (rd->week - 1) * 7;
        if (rd->week == 5) {
            if (rd->month == 12)
                next = tz_days_from_civil(year + 1, 1, 1);
            else
                next = tz_days_from_civil(year, rd->month + 1, 1);
            while (day >= next)
                day -= 7;
        }
        return day;
    }
}

/* k-th transition generated by the rule (k >= 0) */
static void tz_rule_get(const TZRule *r, int64_t k, int64_t *ptime,
                        int *poffset)
{
    int64_t year = r->first_year + k / 2;
    int64_t start, end;

    start = tz_rule_day(&r->start, year) * 86400 + r->start.secs - r->std_offset;
    end = tz_rule_day(&r->end, year) * 86400 + r->end.secs - r->dst_offset;
    if ((start < end) == ((k & 1) == 0)) {
        *ptime = start;
        *poffset = r->dst_offset;
    } else {
        *ptime = end;
        *poffset = r->std_offset;
    }
}

static int64_t tz_rule_time(const TZRule *r, int64_t k)
{
    int64_t t;
    int offset;
    tz_rule_get(r, k, &t, &offset);
    return t;
}

static void tz_get_tr(const TZView *v, int64_t i, int64_t *ptime, int *poffset)
{
    if (i < v->n) {
        *ptime = v->tr[i].start_sec;
        *poffset = v->tr[i].offset_sec;
    } else {
        tz_rule_get(v->rule, v->rule->first_index + (i - v->n), ptime, poffset);
    }
}

static int64_t tz_get_time(const TZView *v, int64_t i)
{
    int64_t t;
    int offset;
    tz_get_tr(v, i, &t, &offset);
    return t;
}

static int tz_get_offset(const TZView *v, int64_t i)
{
    int64_t t;
    int offset;
    tz_get_tr(v, i, &t, &offset);
    return offset;
}

static BOOL tz_has_tr(const TZView *v, int64_t i)
{
    return i < v->n || v->rule != NULL;
}

/* number of transitions at or before 't' */
static int64_t tz_count_le(const TZView *v, int64_t t)
{
    const TZRule *r = v->rule;
    int lo, hi, mid;
    int64_t k;

    lo = 0;
    hi = v->n;
    while (lo < hi) {
        mid = (lo + hi) >> 1;
        if (v->tr[mid].start_sec <= t)
            lo = mid + 1;
        else
            hi = mid;
    }
    if (lo < v->n || !r)
        return lo;
    if (t > TZ_RULE_MAX_SEC)
        t = TZ_RULE_MAX_SEC;
    /* two rule transitions per year: start from the previous year */
    k = 2 * (tz_year_from_days(tz_floor_div(t, 86400)) - r->first_year) - 2;
    if (k < r->first_index)
        k = r->first_index;
    while (k > r->first_index && tz_rule_time(r, k) > t)
        k--;
    if (tz_rule_time(r, k) > t)
        return v->n;
    while (tz_rule_time(r, k + 1) <= t)
        k++;
    return v->n + (k - r->first_index) + 1;
}

